export function buildVideoRow(video, index) {
  return {
    id: video.id,
    title: video.title,
    description: video.description,
    category: video.category,
    tags: video.tags,
    creator_id: video.creator_id,
    thumbnail: THUMBNAILS[index % THUMBNAILS.length],
    videoUrl: SAMPLE_VIDEOS[index % SAMPLE_VIDEOS.length],
    views: video.views,
    duration: video.duration,
    is_short: false,
    gostei_muito: Math.floor(video.views * 0.015),
    gostei: Math.floor(video.views * 0.04),
    nao_gostei: Math.floor(video.views * 0.003),
    is_community_suggestion: false,
    created_at: new Date(Date.now() - video.daysAgo * 86400000).toISOString(),
  };
}
